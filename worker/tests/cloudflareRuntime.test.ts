// Locate local D1 SQLite file generated by Wrangler
function findLocalD1SqliteFile(): string {
  const d1Dir = path.resolve(__dirname, '../.wrangler/state/v3/d1/miniflare-D1DatabaseObject');
  if (!fs.existsSync(d1Dir)) {
    throw new Error(`D1 directory not found at ${d1Dir}`);
  }
  const files = fs.readdirSync(d1Dir);
  const sqliteFile = files.find((f) => f.endsWith('.sqlite') && f !== 'metadata.sqlite');
  if (!sqliteFile) {
    throw new Error(`No D1 sqlite database file found in ${d1Dir}`);
  }
  return path.join(d1Dir, sqliteFile);
}

